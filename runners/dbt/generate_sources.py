"""
Generate dbt source definitions and key tests from the primary key registry.

Reads active entries from validation_sweep.metadata.pk_registry and writes models/sources.yml, 
so dbt validates the same tables and keys as the other runners.
Each registry entry gets two custom tests whose failure counts match the results table definitions: 
pk_null_rows (null_key_count) and pk_extra_rows (duplicate_count). 
Requires DATABRICKS_HOST, DATABRICKS_HTTP_PATH and DATABRICKS_TOKEN to be set.
"""
import os
from pathlib import Path

import yaml
from databricks import sql

OUTPUT_FILE = Path(__file__).parent / "models" / "sources.yml"

with sql.connect(
    server_hostname=os.environ["DATABRICKS_HOST"],
    http_path=os.environ["DATABRICKS_HTTP_PATH"],
    access_token=os.environ["DATABRICKS_TOKEN"],
) as connection:
    with connection.cursor() as cursor:
        cursor.execute("""
            select catalog_name, schema_name, table_name, key_columns
            from validation_sweep.metadata.pk_registry
            where is_active
            order by catalog_name, schema_name, table_name
        """)
        registry = cursor.fetchall()

# Group registry entries into one dbt source per catalog and schema
sources = {}
for row in registry:
    key_columns = [str(c) for c in row.key_columns]
    full_name = f"{row.catalog_name}.{row.schema_name}.{row.table_name}"

    source = sources.setdefault(
        (row.catalog_name, row.schema_name),
        {"name": row.schema_name, "database": row.catalog_name,
         "schema": row.schema_name, "tables": {}},
    )
    table = source["tables"].setdefault(
        row.table_name, {"name": row.table_name, "data_tests": []}
    )

    # Two tests per registry entry; metadata tells the loader what each one measures
    for test_name, metric in [("pk_null_rows", "null_key_count"),
                              ("pk_extra_rows", "duplicate_count")]:
        table["data_tests"].append({
            test_name: {
                "arguments": {"key_columns": key_columns},
                "config": {"meta": {"table_name": full_name,
                                    "key_columns": key_columns,
                                    "metric": metric}},
            }
        })

# Convert the nested dictionaries into the list structure dbt expects
document = {"version": 2, "sources": []}
for source in sources.values():
    tables = list(source["tables"].values())
    document["sources"].append({**source, "tables": tables})

OUTPUT_FILE.parent.mkdir(exist_ok=True)
header = "# Generated by generate_sources.py from pk_registry. Do not edit by hand.\n"
OUTPUT_FILE.write_text(header + yaml.safe_dump(document, sort_keys=False))
print(f"Wrote {len(registry)} registry entries to {OUTPUT_FILE}")